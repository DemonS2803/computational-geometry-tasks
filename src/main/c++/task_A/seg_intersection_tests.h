#pragma once
#include <vector>
#include <cassert>

using namespace std;

// Локальная заглушка для разработки.
// На сервере используется настоящая версия из /usr/include/seg_intersection_tests.h

vector < double > genTest(int testId) {
    assert(testId >= 1 && testId <= 10);

    // 3 test cases per testId
    // Each test case: 2 segments, 4 points = 8 doubles
    // Segment 1: (x1,y1)-(x2,y2), Segment 2: (x3,y3)-(x4,y4)
    switch (testId) {
        // 1. Два пересекающихся отрезка (крест) — Y
        case 1:
            return {
                0, 0,   4, 4,   0, 4,   4, 0,
                2, 2,   3, 3,   5, 5,   6, 6,
                1, 0,   0, 1,   1, 1,   0, 0
            };
        // 2. Касание в конце первого / начале второго (Y-shape) — Y
        case 2:
            return {
                0, 0,   2, 2,   2, 2,   4, 0,
                3, 0,   5, 2,   5, 2,   7, 0,
                1, 1,   2, 2,   2, 2,   3, 3
            };
        // 3. Пересекающиеся отрезки в середине — Y
        case 3:
            return {
                1, 0,   3, 2,   0, 3,   4, 1,
                -1, -1,  1, 1,   1, 3,  -1, 1,
                0, 0,   2, 2,   1, -1,  3, 1
            };
        // 4. Коллинеарные, перекрываются — Y
        case 4:
            return {
                0, 0,   4, 0,   1, 0,   3, 0,
                2, 2,   6, 2,   3, 2,   5, 2,
                -1, -1,  3, 3,   0, 0,   2, 2
            };
        // 5. Параллельные, не касаются — N
        case 5:
            return {
                0, 0,   2, 0,   3, 0,   5, 0,
                0, 1,   2, 1,   3, 1,   5, 1,
                1, 0,   1, 2,   3, 0,   3, 2
            };
        // 6. Коллинеарные, не перекрываются — N
        case 6:
            return {
                0, 0,   1, 0,   2, 0,   3, 0,
                0, 0,   1, 1,   2, 2,   3, 3,
                1, 0,   2, 0,   3, 0,   4, 0
            };
        // 7. Пересекаются под прямым углом (T-junction) — Y
        case 7:
            return {
                0, 1,   2, 1,   1, 0,   1, 2,
                3, 0,   5, 0,   4, -1,  4, 1,
                0, 0,   0, 3,   2, 1,   2, 2
            };
        // 8. Один отрезок внутри другого (вложенность) — Y
        case 8:
            return {
                0, 0,   5, 5,   1, 1,   4, 4,
                1, 1,   6, 6,   2, 2,   5, 5,
                -2, -2,  2, 2,   0, 0,   1, 1
            };
        // 9. Касание концами двух отрезков — Y
        case 9:
            return {
                0, 0,   1, 1,   1, 1,   2, 2,
                0, 2,   2, 0,   2, 0,   4, 2,
                -1, -1,  0, 0,   0, 0,   1, 1
            };
        // 10. Пересекаются, один горизонтальный, другой вертикальный — Y
        case 10:
            return {
                0, 2,   4, 2,   2, 0,   2, 4,
                1, 0,   3, 0,   2, -1,  2, 1,
                0, 0,   2, 2,   1, 0,   1, 2
            };
    }
    return {};
}
